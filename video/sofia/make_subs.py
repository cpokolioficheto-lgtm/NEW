"""Генерира sofia/subs.ass (стил „Мокри помещения“). [думи] = акцент в тюркоазено, | = нов ред."""
import os, re, sys
sys.argv = sys.argv[:1] + ['x', 'x']; os.environ['ASS'] = 'x'  # само за HEAD/POP/ts
here = os.path.dirname(os.path.abspath(__file__))
src = open(os.path.join(here, '..', 'process.py'), encoding='utf-8').read()
HEAD = re.search(r"HEAD = f'''(.*?)'''", src, re.S).group(1).replace('{W}', '1080').replace('{H}', '1920')
POP = '{\\fscx85\\fscy85\\t(0,140,\\fscx100\\fscy100)}'
ACC, WHITE = '{\\c&H00B5B51C&}', '{\\c&H00FFFFFF&}'
LINES = [
    (0.98, 2.80, 'СТЯГАМЕ БАГАЖА.'),
    (2.82, 4.34, 'ЦЕНТЪР ЗА|ПРОФЕСИОНАЛНО ОБУЧЕНИЕ'),
    (4.34, 6.80, '[„КОЛЬО ФИЧЕТО“]|ОТИВА В [СОФИЯ]!'),
    (8.48, 9.70, 'КУРСЪТ ПО|[МИКРОЦИМЕНТ]'),
    (9.70, 11.50, 'ВЕЧЕ НЕ Е САМО|ВЪВ ВАРНА.'),
    (11.68, 13.32, '[4 И 5 ДЕКЕМВРИ]'),
    (13.32, 15.40, 'СИСТЕМА [MICRONE]|НА [CEMHER]'),
    (16.92, 18.00, 'НЕ ГЛЕДАШ|ОТСТРАНИ –'),
    (18.32, 20.30, 'УЧИШ СЕ|И ПРИЛАГАШ.'),
    (21.46, 22.80, 'ДО КРАЯ НА|[ОКТОМВРИ]'),
    (22.80, 24.18, 'ПРОМОЦИОНАЛНА|ЦЕНА:'),
    (24.18, 25.85, 'ВМЕСТО 600 ЕВРО,'),
    (25.90, 28.30, 'ПОЛУЧАВАШ КУРСА|ЗА [500 ЕВРО]!'),
    (30.60, 33.10, 'ПИШИ НИ [„СОФИЯ“]|В СЪОБЩЕНИЕ,'),
    (33.32, 34.96, 'ЗАПИШИ СЕ И|СЕ ВЪЗПОЛЗВАЙ'),
    (34.96, 36.40, 'ОТ НАШАТА|[ПРОМОЦИЯ]!'),
]
def ts(t):
    m, s = divmod(t, 60); return f'0:{int(m):02d}:{s:05.2f}'
with open(os.path.join(here, 'subs.ass'), 'w', encoding='utf-8') as f:
    f.write(HEAD)
    for a, z, t in LINES:
        t = t.replace('[', ACC).replace(']', WHITE).replace('|', '\\N')
        f.write(f'Dialogue: 0,{ts(a)},{ts(z)},Sub,,0,0,0,,{POP}{t}\n')
